// Flattens the Web Awesome stylesheet import graph into a single CSS file so
// it can be consumed by the Tailwind/PostCSS pipeline (which otherwise chokes
// on the package's relative `@import url()` chains in dev mode).
//
// Usage: node scripts/bundle-webawesome-css.mjs

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const pkg = resolve(root, "node_modules/@awesome.me/webawesome/dist/styles");

const ENTRY_FILES = ["themes/default.css", "utilities.css"];

const visited = new Set();
const layerStatements = [];
const body = [];

function inline(filePath) {
  if (visited.has(filePath)) return;
  visited.add(filePath);
  const source = readFileSync(filePath, "utf8");
  const importPattern = /@import\s+(?:url\((['"])(.*?)\1\)|(['"])(.*?)\3)\s*;/g;
  let lastIndex = 0;
  let match;
  while ((match = importPattern.exec(source)) !== null) {
    body.push(source.slice(lastIndex, match.index));
    const target = match[2] ?? match[4];
    inline(resolve(dirname(filePath), target));
    lastIndex = importPattern.lastIndex;
  }
  const rest = source.slice(lastIndex);
  const statements = rest.match(/@layer\s+[^;{}]+;/g) ?? [];
  for (const statement of statements) {
    if (!layerStatements.includes(statement)) layerStatements.push(statement);
  }
  body.push(rest);
}

for (const entry of ENTRY_FILES) inline(resolve(pkg, entry));

const banner =
  "/* Auto-generated by scripts/bundle-webawesome-css.mjs from " +
  "@awesome.me/webawesome/dist/styles. Do not edit by hand. */\n";
const output = banner + layerStatements.join("\n") + "\n" + body.join("\n");

const outDir = resolve(root, "src/styles");
mkdirSync(outDir, { recursive: true });
const outFile = resolve(outDir, "webawesome.css");
writeFileSync(outFile, output);
console.log(
  `Wrote ${outFile} (${output.length} bytes, ${visited.size} source files inlined)`,
);
